export function getBodyLines(style: SelfieStyle): string[] {
  return style === "tease" || style === "chunyu" ? DOUBAO_BODY : NON_DOUBAO_BODY;
}

export function getStyleBlock(style: SelfieStyle): StyleBlock {
  switch (style) {
    case "glam":
      return GLAM_BLOCK;
    case "chunyu":
      return CHUNYU_BLOCK;
    case "tease":
      return TEASE_BLOCK;
    default:
      return COZY_BLOCK;
  }
}

